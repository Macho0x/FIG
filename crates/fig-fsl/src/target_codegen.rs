fn json_schema_type(ft: &FieldType, schema: &Schema) -> &'static str {
    match ft {
        FieldType::Named(name) => {
            if let Some(bt) = resolve_named_type(name, schema) {
                match bt {
                    BaseType::String | BaseType::Bytes => "string",
                    BaseType::Bool => "boolean",
                    _ => "number",
                }
            } else {
                "string"
            }
        }
        FieldType::Enum(_) => "integer",
        FieldType::List(_) => "array",
        FieldType::InlineStruct(_) => "object",
        FieldType::InlineBase(bt, _) => match bt {
            BaseType::String | BaseType::Bytes => "string",
            BaseType::Bool => "boolean",
            BaseType::List(_) => "array",
            _ => "number",
        },
    }
}
