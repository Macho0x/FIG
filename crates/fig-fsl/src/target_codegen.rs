impl JsonSchemaCodegen {
    pub fn generate(schema: &Schema) -> String {
        let mut out = String::new();
        out.push_str(&format!(
            "{{\n  \"$schema\": \"https://json-schema.org/draft/2020-12/schema\",\n  \"title\": \"{}\",\n  \"version\": \"{}\",\n  \"definitions\": {{\n",
            schema.name, schema.version
        ));

        for (i, msg) in schema.messages.iter().enumerate() {
            out.push_str(&format!("    \"{}\": {{\n      \"type\": \"object\",\n      \"properties\": {{\n", msg.name));
            for field in &msg.fields {
                let json_type = json_schema_type(&field.field_type, schema);
                out.push_str(&format!(
                    "        \"{}\": {{ \"type\": \"{}\" }},\n",
                    field.name, json_type
                ));
            }
            out.push_str("      }\n    }");
            if i + 1 < schema.messages.len() {
                out.push(',');
            }
            out.push('\n');
        }
        out.push_str("  }\n}\n");
        out
    }
}

