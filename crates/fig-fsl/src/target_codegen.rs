fn pascal_case(s: &str) -> String {
    s.split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

fn snake_to_camel(s: &str) -> String {
    let parts: Vec<&str> = s.split('_').collect();
    if parts.is_empty() {
        return String::new();
    }
    let first = parts[0];
    let rest = parts
        .iter()
        .skip(1)
        .map(|p| pascal_case(p))
        .collect::<Vec<_>>()
        .join("");
    format!("{}{}", first, rest)
}

fn proto_package_name(name: &str) -> String {
    name.replace('.', "_")
}

fn resolve_named_type(name: &str, schema: &Schema) -> Option<BaseType> {
    schema
        .type_defs
        .iter()
        .find(|td| td.name == name)
        .and_then(|td| td.base_type.clone())
}

fn go_base_type(bt: &BaseType) -> String {
    match bt {
        BaseType::String => "string".to_string(),
        BaseType::Int8 => "int8".to_string(),
        BaseType::Int16 => "int16".to_string(),
        BaseType::Int32 => "int32".to_string(),
        BaseType::Int64 => "int64".to_string(),
        BaseType::UInt8 => "uint8".to_string(),
        BaseType::UInt16 => "uint16".to_string(),
        BaseType::UInt32 => "uint32".to_string(),
        BaseType::UInt64 => "uint64".to_string(),
        BaseType::Float32 => "float32".to_string(),
        BaseType::Float64 => "float64".to_string(),
        BaseType::Decimal64 => "float64".to_string(),
        BaseType::Bool => "bool".to_string(),
        BaseType::Bytes => "[]byte".to_string(),
        BaseType::List(inner) => format!("[]{}", go_base_type(inner)),
    }
}

fn go_field_type(ft: &FieldType, schema: &Schema, msg_name: &str, optional: bool) -> String {
    let base = match ft {
        FieldType::Named(name) => {
            if let Some(bt) = resolve_named_type(name, schema) {
                go_base_type(&bt)
            } else {
                match name.as_str() {
                    "Price" | "Quantity" => "float64".to_string(),
                    "TradeTimestamp" => "int64".to_string(),
                    _ => "string".to_string(),
                }
            }
        }
        FieldType::Enum(_) => "int32".to_string(),
        FieldType::List(inner) => format!("[]{}", go_field_type(inner, schema, msg_name, false)),
        FieldType::InlineStruct(_) => format!("{}{}", msg_name, pascal_case("inline")),
        FieldType::InlineBase(bt, _) => go_base_type(bt),
    };
    if optional {
        format!("*{}", base)
    } else {
        base
    }
}

