//! Multi-target schema codegen (Go, Protobuf, SBE XML, C++, C#).
//!
//! Generates message struct definitions from FSL AST — focused on
//! `schema.messages` fields with BaseType → target type mapping.

use crate::ast::*;

/// Go struct generator with JSON tags
pub struct GoCodegen;

/// Protobuf `.proto` file generator
pub struct ProtoCodegen;

/// SBE XML `messageSchema` generator
pub struct SbeXmlCodegen;

/// C++ struct generator
pub struct CppCodegen;

/// C# class generator
pub struct CsharpCodegen;

/// Python dataclass generator
pub struct PythonCodegen;

/// TypeScript interface generator
pub struct TypeScriptCodegen;

/// OCaml record generator
pub struct OcamlCodegen;

/// Zig struct generator
pub struct ZigCodegen;

/// JSON Schema generator
pub struct JsonSchemaCodegen;

/// FIX mapping YAML generator
pub struct FixYamlCodegen;

impl GoCodegen {
    pub fn generate(schema: &Schema) -> String {
        let mut out = String::new();
        let desc = schema
            .description
            .as_deref()
            .unwrap_or(&schema.name);
        out.push_str(&format!(
            "// Auto-generated by fig-fsl from schema '{}' v{}\n",
            schema.name, schema.version
        ));
        out.push_str(&format!("// {}\n\n", desc));
        out.push_str("package generated\n\n");

        for msg in &schema.messages {
            out.push_str(&format!("// Message: {}\n", msg.name));
            out.push_str(&format!("type {} struct {{\n", msg.name));
            for field in &msg.fields {
                let go_type = go_field_type(&field.field_type, schema, &msg.name, field.optional);
                let field_name = pascal_case(&field.name);
                out.push_str(&format!(
                    "    {} {} `json:\"{}\"`\n",
                    field_name, go_type, field.name
                ));
            }
            out.push_str("}\n\n");
        }
        out
    }
}

impl ProtoCodegen {
    pub fn generate(schema: &Schema) -> String {
        let mut out = String::new();
        let desc = schema
            .description
            .as_deref()
            .unwrap_or(&schema.name);
        out.push_str(&format!(
            "// Auto-generated by fig-fsl from schema '{}' v{}\n",
            schema.name, schema.version
        ));
        out.push_str(&format!("// {}\n\n", desc));
        out.push_str("syntax = \"proto3\";\n\n");
        out.push_str(&format!("package {};\n\n", proto_package_name(&schema.name)));

        for msg in &schema.messages {
            out.push_str(&format!("// Message: {}\n", msg.name));
            out.push_str(&format!("message {} {{\n", msg.name));
            for field in &msg.fields {
                let proto_type =
                    proto_field_type(&field.field_type, schema, &msg.name, field.optional);
                let number = field.number.unwrap_or(0);
                if field.optional {
                    out.push_str(&format!(
                        "  optional {} {} = {};\n",
                        proto_type, field.name, number
                    ));
                } else {
                    out.push_str(&format!("  {} {} = {};\n", proto_type, field.name, number));
                }
            }
            out.push_str("}\n\n");
        }
        out
    }
}

impl SbeXmlCodegen {
    pub fn generate(schema: &Schema) -> String {
        let mut out = String::new();
        let desc = schema
            .description
            .as_deref()
            .unwrap_or(&schema.name);
        out.push_str(&format!(
            "<!-- Auto-generated by fig-fsl from schema '{}' v{} -->\n",
            schema.name, schema.version
        ));
        out.push_str(&format!("<!-- {} -->\n", desc));
        out.push_str(
            "<sbe:messageSchema xmlns:sbe=\"http://fixprotocol.io/2016/sbe\"\n",
        );
        out.push_str(&format!(
            "                   package=\"{}\"\n",
            schema.name.replace('.', "_")
        ));
        let schema_id = schema.well_known_id.unwrap_or(1);
        out.push_str(&format!("                   id=\"{}\"\n", schema_id));
        out.push_str("                   version=\"0\"\n");
        out.push_str(&format!(
            "                   semanticVersion=\"{}\"\n",
            schema.version
        ));
        out.push_str("                   byteOrder=\"littleEndian\">\n\n");
        out.push_str("  <types>\n");
        out.push_str("    <composite name=\"messageHeader\" description=\"Message identifiers and length of message root\">\n");
        out.push_str("      <type name=\"blockLength\" primitiveType=\"uint16\"/>\n");
        out.push_str("      <type name=\"templateId\" primitiveType=\"uint16\"/>\n");
        out.push_str("      <type name=\"schemaId\" primitiveType=\"uint16\"/>\n");
        out.push_str("      <type name=\"version\" primitiveType=\"uint16\"/>\n");
        out.push_str("    </composite>\n");
        out.push_str("  </types>\n\n");

        for (template_id, msg) in schema.messages.iter().enumerate() {
            let tid = template_id + 1;
            out.push_str(&format!("  <message name=\"{}\" id=\"{}\">\n", msg.name, tid));
            for field in &msg.fields {
                let sbe_type = sbe_xml_field_type(&field.field_type, schema);
                let presence = if field.optional { "optional" } else { "required" };
                let field_id = field.number.unwrap_or(0);
                let sbe_name = snake_to_camel(&field.name);
                out.push_str(&format!(
                    "    <field name=\"{}\" id=\"{}\" type=\"{}\" presence=\"{}\"/>\n",
                    sbe_name, field_id, sbe_type, presence
                ));
            }
            out.push_str("  </message>\n\n");
        }
        out.push_str("</sbe:messageSchema>\n");
        out
    }
}

